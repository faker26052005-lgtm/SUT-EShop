#!/usr/bin/env node
/**
 * Reads reports/_json/*.json (written by every run) and prints / writes the numbers needed for README.md:
 * features, test cases automated / executed / passed / failed, number of browser runs, failing tests.
 * Output: stdout and docs/test-summary.md
 */
const fs = require('fs');
const path = require('path');

const dir = path.join('reports', '_json');
if (!fs.existsSync(dir)) {
  console.error('No reports/_json folder yet. Run a matrix first: node scripts/run-matrix.js <feature>');
  process.exit(1);
}

function walk(suite, cb) {
  (suite.specs || []).forEach((spec) => spec.tests.forEach((t) => cb(spec, t)));
  (suite.suites || []).forEach((s) => walk(s, cb));
}

const runs = [];
for (const file of fs.readdirSync(dir).filter((f) => f.endsWith('.json') && f !== 'latest.json').sort()) {
  const json = JSON.parse(fs.readFileSync(path.join(dir, file), 'utf8'));
  const run = { slug: file.replace(/\.json$/, ''), passed: 0, failed: 0, skipped: 0, flaky: 0, clarify: 0, failures: [] };
  (json.suites || []).forEach((s) =>
    walk(s, (spec, t) => {
      if (t.status === 'expected') run.passed++;
      else if (t.status === 'unexpected') {
        run.failed++;
        run.failures.push(spec.title);
      } else if (t.status === 'flaky') run.flaky++;
      else run.skipped++;
      if ((t.annotations || []).some((a) => a.type === 'CLARIFY')) run.clarify++;
    }),
  );
  run.total = run.passed + run.failed + run.skipped + run.flaky;
  runs.push(run);
}

const features = [...new Set(runs.map((r) => r.slug.split('-')[0]))];
const lines = [];
lines.push('# Test summary (generated by `npm run summary`)', '');
lines.push('| Run | Executed | Passed | Failed | Skipped | Flaky | Recorded as CLARIFY |');
lines.push('| :-- | --: | --: | --: | --: | --: | --: |');
for (const r of runs) lines.push(`| ${r.slug} | ${r.total} | ${r.passed} | ${r.failed} | ${r.skipped} | ${r.flaky} | ${r.clarify} |`);

lines.push('', '## Per feature (test cases automated = test cases in one browser run)', '');
lines.push('| Feature | Automated | Browser runs | Executed (all runs) | Passed | Failed |');
lines.push('| :-- | --: | --: | --: | --: | --: |');
for (const f of features) {
  const rs = runs.filter((r) => r.slug.startsWith(f + '-'));
  const sum = (k) => rs.reduce((a, r) => a + r[k], 0);
  lines.push(`| ${f.toUpperCase()} | ${rs[0].total} | ${rs.length} | ${sum('total')} | ${sum('passed')} | ${sum('failed')} |`);
}
const MIN_RUNS = Number(process.env.MIN_RUNS || 0); // set MIN_RUNS=9 if the course requires a minimum number of runs
lines.push('', `Browser runs: **${runs.length}**${MIN_RUNS ? ` (need >= ${MIN_RUNS})` : ''}. Features: **${features.length}**.`);

const failing = {};
for (const r of runs) for (const t of r.failures) (failing[t] ||= []).push(r.slug.split('-').slice(1).join('-'));
lines.push('', '## Failing tests (candidate bugs - confirm each one by hand before opening an issue)', '');
if (!Object.keys(failing).length) lines.push('None.');
for (const [title, browsers] of Object.entries(failing)) lines.push(`- ${title} - failed on: ${browsers.join(', ')}`);

const out = lines.join('\n') + '\n';
fs.mkdirSync('docs', { recursive: true });
fs.writeFileSync(path.join('docs', 'test-summary.md'), out, 'utf8');
console.log(out);
